import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const results = path.join(root, 'test-results');
fs.mkdirSync(results, { recursive: true });
const fixture = fs.mkdtempSync(path.join(results, 'publish-'));
fs.mkdirSync(path.join(fixture, 'scripts'));
fs.mkdirSync(path.join(fixture, 'assets'));
for (const file of ['scripts/build-site.mjs', 'assets/catalog-products.js', 'assets/pages.js', 'assets/lens-pages.js', 'assets/app.js', 'assets/site.css']) fs.copyFileSync(path.join(root, file), path.join(fixture, file));
fs.cpSync(path.join(root, 'assets/catalogo'), path.join(fixture, 'assets/catalogo'), { recursive: true });
const config = JSON.parse(fs.readFileSync(path.join(root, 'site-config.json'), 'utf8'));
config.siteUrl = '';
const save = () => fs.writeFileSync(path.join(fixture, 'site-config.json'), JSON.stringify(config));
const build = () => spawnSync(process.execPath, [path.join(fixture, 'scripts/build-site.mjs'), '--publish'], { encoding: 'utf8' });
save();
assert.notEqual(build().status, 0, 'publicação não pode aceitar domínio ausente');
config.siteUrl = 'https://example.invalid/pupila';
for (const key of Object.keys(config.privacy)) config.privacy[key] = '';
save();
assert.notEqual(build().status, 0, 'publicação não pode aceitar política incompleta');
// Valores fictícios confinados à fixture, nunca aos arquivos do site.
config.privacy = { legalName: 'Empresa de teste & exemplo', cnpj: '00.000.000/0000-00', address: 'Endereço de teste', contact: 'privacidade@example.invalid', hosting: 'Host de teste', hostingCountry: 'País de teste', logRetention: 'Retenção de teste', reviewedOn: '04/11/2026' };
save();
const result = build();
assert.equal(result.status, 0, result.stderr);
const dist = path.join(fixture, 'dist');
const html = fs.readFileSync(path.join(dist, 'contato/index.html'), 'utf8');
assert(html.includes('rel="canonical" href="https://example.invalid/pupila/contato/"'));
assert(html.includes('property="og:image" content="https://example.invalid/pupila/assets/social-pupila.jpg"'));
const privacy = fs.readFileSync(path.join(dist, 'privacidade/index.html'), 'utf8');
assert(privacy.includes('Empresa de teste &amp; exemplo') && privacy.includes('privacidade@example.invalid'));
assert(!privacy.includes('Esta prévia aguarda'));
const sitemap = fs.readFileSync(path.join(dist, 'sitemap.xml'), 'utf8');
assert.equal((sitemap.match(/<url>/g) || []).length, 74);
const catalogPhotos = fs.readdirSync(path.join(dist, 'assets/catalogo'), { recursive: true }).filter(file => file.endsWith('.webp'));
assert.equal(catalogPhotos.length, 178, 'fotos WebP do catálogo ausentes no pacote');
assert(!sitemap.includes('404.html') && !sitemap.includes('marcas/modelo'));
assert(fs.readFileSync(path.join(dist, 'robots.txt'), 'utf8').includes('Sitemap: https://example.invalid/pupila/sitemap.xml'));
for (const file of ['site-config.json','package.json','docs','scripts','assets/catalog-products.js','assets/pages.js','assets/lens-pages.js']) assert(!fs.existsSync(path.join(dist,file)), `${file} exposto na publicação`);
console.log('✓ Publicação: rejeita dados ausentes; gera canonical, sitemap, imagem social e política em fixture isolada');
